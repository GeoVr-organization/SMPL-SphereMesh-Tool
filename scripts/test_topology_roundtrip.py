class FakeProperty:
    def __init__(self):
        self.color = None
        self.opacity = None

    def SetColor(self, color):
        self.color = tuple(color)

    def SetOpacity(self, opacity):
        self.opacity = float(opacity)


class FakeSphereWidget:
    def __init__(self, center, radius):
        self.center = tuple(float(value) for value in center)
        self.radius = float(radius)
        self.enabled = True
        self.sphere_property = FakeProperty()

    def SetCenter(self, center):
        self.center = tuple(float(value) for value in center)

    def SetRadius(self, radius):
        self.radius = float(radius)

    def GetRadius(self):
        return self.radius

    def GetSphereProperty(self):
        return self.sphere_property

    def On(self):
        self.enabled = True

    def Off(self):
        self.enabled = False


class FakeMapper:
    def __init__(self):
        self.input_data = None

    def SetInputData(self, data):
        self.input_data = data


class FakeActor:
    def __init__(self, mesh):
        self.mesh = mesh
        self.visible = True
        self.actor_property = FakeProperty()
        self.mapper = FakeMapper()

    def SetVisibility(self, visible):
        self.visible = bool(visible)

    def GetProperty(self):
        return self.actor_property

    def GetMapper(self):
        return self.mapper


class FakePlotter:
    """Duck-type of the pyvistaqt interactor surface ``SphereManager`` touches."""

    def __init__(self):
        self.sphere_widgets: list[FakeSphereWidget] = []
        self.actors: list[FakeActor] = []
        self.render_calls = 0

    def add_sphere_widget(self, callback, center, radius, **_options):
        widget = FakeSphereWidget(center, radius)
        widget.callback = callback
        self.sphere_widgets.append(widget)
        return widget

    def add_mesh(self, mesh, **_options):
        actor = FakeActor(mesh)
        self.actors.append(actor)
        return actor

    def remove_actor(self, actor):
        if actor in self.actors:
            self.actors.remove(actor)

    def clear_sphere_widgets(self):
        self.sphere_widgets.clear()

    def render(self):
        self.render_calls += 1


# ------------------------------------------------------------------ helpers


def make_skeleton(body: anatomy.Body) -> Skeleton:
    return Skeleton(body.joints, body.parents, body.rotations, rs_are_global=True)


def make_manager(rest_body: anatomy.Body) -> tuple[SphereManager, FakePlotter]:
    plotter = FakePlotter()
    manager = SphereManager(plotter, lambda: None)
    manager.rest_skeleton = make_skeleton(rest_body)
    manager.skeleton = make_skeleton(rest_body)
    return manager, plotter


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def loaded_centers(manager: SphereManager) -> np.ndarray:
    return np.array([sphere.get_center() for sphere in manager.spheres], dtype=np.float64)


def loaded_radii(manager: SphereManager) -> np.ndarray:
    return np.array([sphere.get_radius() for sphere in manager.spheres], dtype=np.float64)


def loaded_connections(manager: SphereManager) -> list[tuple[int, ...]]:
    return [tuple(connection.sphere_indices) for connection in manager.connections]


def snapshot_bindings(manager: SphereManager) -> list[dict]:
    snapshot = []
    for sphere in manager.spheres:
        snapshot.append({
            "parent_joint": sphere.get_parent_joint(),
            "rest_offset": sphere.get_rest_offset(),
            "secondary_joint": sphere.get_secondary_joint(),
            "lbs_weight": sphere.get_lbs_weight(),
        })
    return snapshot


def binding_differences(before: list[dict], after: list[dict], tolerance: float) -> list[int]:
    differing = []
    for index, (old, new) in enumerate(zip(before, after)):
        if old["parent_joint"] != new["parent_joint"]:
            differing.append(index)
            continue
        if old["rest_offset"] is None or new["rest_offset"] is None:
            differing.append(index)
            continue
        if np.abs(old["rest_offset"] - new["rest_offset"]).max() > tolerance:
            differing.append(index)
    return differing


