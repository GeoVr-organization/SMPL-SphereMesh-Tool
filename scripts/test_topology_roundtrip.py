    class Skeleton:
        """Minimal stand-in with the semantics of ``src.ui_widgets.Skeleton``.

        ``joints`` are world positions, ``kintree`` the parent index per joint and ``Rs``
        the *global* rotation per joint; ``get_joint_rotation`` returns that global
        rotation, which is all ``SphereManager`` reads.
        """

        def __init__(self, joints, kintree, Rs, *, rs_are_global: bool = True):
            self.joints = joints
            self.kintree = np.asarray(kintree, dtype=np.int64).reshape(-1)
            self.Rs = np.asarray(Rs, dtype=np.float64)
            if rs_are_global:
                self.global_Rs = self.Rs
            else:
                self.global_Rs = np.zeros_like(self.Rs)
                self.global_Rs[0] = self.Rs[0]
                for joint_index in range(1, len(self.kintree)):
                    parent_index = int(self.kintree[joint_index])
                    self.global_Rs[joint_index] = (
                        self.Rs[joint_index] if parent_index < 0
                        else self.global_Rs[parent_index] @ self.Rs[joint_index]
                    )

        def get_joint_rotation(self, joint_index):
            return self.global_Rs[joint_index]


