# 6. json2txt on a file without quad_groups, and the txt -> json -> txt round trip ----
print("6. json2txt / txt2json on files without quad_groups")
from txt2json import convert_text_to_json_payload  # noqa: E402

with warnings.catch_warnings():
    warnings.simplefilter("ignore")
    template_text_now = convert_json_to_text(TEMPLATE_JSON, "Sphere Mesh 2.0")
template_text_reference = TEMPLATE_TEXT.read_text(encoding="utf-8")
# data/template.txt was written by the previous json2txt, whose ``math.trunc(x * 10000)``
# truncated one unit low whenever the product landed an ulp under an integer (0.348 ->
# 0.3479). The exact truncation now in use differs from that file on precisely those
# tokens and nowhere else; every other byte must still match.
old_lines = template_text_reference.splitlines()
new_lines = template_text_now.splitlines()
truncation_artefacts = 0
other_differences = 0
for old_line, new_line in zip(old_lines, new_lines):
    if old_line == new_line:
        continue
    old_tokens, new_tokens = old_line.split(), new_line.split()
    for old_token, new_token in zip(old_tokens, new_tokens):
        if old_token == new_token:
            continue
        old_value, new_value = float(old_token), float(new_token)
        is_one_unit_low = abs(abs(new_value) - abs(old_value) - 1e-4) < 1e-12
        if is_one_unit_low and new_value == round(new_value, 4):
            truncation_artefacts += 1
        else:
            other_differences += 1
check(
    len(old_lines) == len(new_lines) and other_differences == 0,
    f"json2txt(template.json) matches data/template.txt except for {truncation_artefacts} "
    f"tokens the old truncation wrote one unit low ({other_differences} other differences)",
)
for label, text_path in (("template.txt", TEMPLATE_TEXT), ("auto_male.txt", GENERATED_TEXT)):
    original_text = text_path.read_text(encoding="utf-8")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        payload = convert_text_to_json_payload(original_text)
    round_trip_path = SCRATCHPAD / f"{text_path.stem}_from_txt.json"
    round_trip_path.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        round_trip_text = convert_json_to_text(round_trip_path, original_text.splitlines()[0])
    check(
        round_trip_text == original_text,
        f"{label}: txt -> json -> txt is byte-identical "
        f"({len(payload.get('quad_groups', []))} quads carried through quad_groups)",
    )

