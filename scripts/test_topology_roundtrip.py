"""Round-trip checks: a generated topology through the tool's own loader, headless.

``src.topology.export`` promises that the JSON it writes opens in ``SphereManager`` with
its bindings intact and moves under a pose exactly as the generator predicted. Those are
claims about *the tool's code*, so this script drives the real ``SphereManager`` -- load,
rebind, pose, save, reload -- against a duck-typed plotter that records widget and actor
calls instead of drawing them. Nothing here is mocked below ``SphereManager``: the sphere
and connection classes, the skeleton class and the SMPL forward pass are the real ones.

It also confirms that ``scripts/json2txt.py`` rebuilds the engine text from the JSON's
``quad_groups`` byte for byte, and states the one place the GUI round trip is still lossy
(``save_to_json`` does not write ``quad_groups``).

Run:  .venv/Scripts/python.exe scripts/test_topology_roundtrip.py
"""
